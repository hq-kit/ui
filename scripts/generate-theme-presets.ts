import type { Preset, ThemeStyleProps } from "@/types/themes"
import { promises as fs } from "node:fs"
import path from "node:path"

const themesDir = path.join(process.cwd(), "lib", "themes", "presets")
const outputFilePath = path.join(process.cwd(), "lib", "themes", "generated.ts")

async function getThemeFileNames() {
  const themes: string[] = []
  const files = await fs.readdir(themesDir)
  for (const file of files) {
    if (file.endsWith(".css")) {
      themes.push(file)
    }
  }
  return themes
}

export async function parseCssToThemeProps(cssString: string): Promise<Preset> {
  const result: Preset = { light: {}, dark: {} }

  const blockRegex = /(:root|\.dark)\s*{([^}]+)}/g
  let blockMatch: RegExpExecArray | null

  // biome-ignore lint/suspicious/noAssignInExpressions: false-positive
  while ((blockMatch = blockRegex.exec(cssString)) !== null) {
    const selector = blockMatch[1]
    const blockContent = blockMatch[2]

    const themeTarget = selector === ":root" ? result.light : result.dark

    const variableRegex = /--([^:]+):\s*([^;]+);/g
    let varMatch: RegExpExecArray | null

    // biome-ignore lint/suspicious/noAssignInExpressions: false-positive
    while ((varMatch = variableRegex.exec(blockContent)) !== null) {
      const key = varMatch[1].trim() as keyof ThemeStyleProps

      themeTarget[key] = varMatch[2].trim()
    }
  }

  return result as Preset
}

type AllThemes = Record<string, Preset>

async function generateThemes() {
  const themeFileNames = await getThemeFileNames()
  const allThemes: AllThemes = {}

  const themeNames: string[] = []

  for (const themeFileName of themeFileNames) {
    const themePath = path.join(themesDir, themeFileName)
    const cssString = await fs.readFile(themePath, "utf8").then(parseCssToThemeProps)

    const themeName = themeFileName.replace(".css", "")
    themeNames.push(themeName)

    allThemes[themeName] = cssString
  }

  const themeNamesUnion = themeNames.length > 0 ? themeNames.map((name) => `'${name}'`).join(" | ") : "string"

  const tsContent = `// This file is autogenerated by scripts/generate-theme-presets.ts.
// Do not edit this file directly.

import type { ThemeStyleProps } from '@/types/themes'

export type ThemeName = ${themeNamesUnion}

export const themes: Record<
  ThemeName,
  {
    light: ThemeStyleProps
    dark: ThemeStyleProps
  }
> = ${JSON.stringify(allThemes, null, 2)};
`

  await fs.writeFile(outputFilePath, tsContent, "utf8")
  console.info(`✓ Generated ${themeNames.length} themes files`)
}

generateThemes()
