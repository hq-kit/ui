import { promises as fs } from "node:fs"
import path from "node:path"
import { type IconLibraryName, iconLibraries } from "shadcn/icons"

type IconUsage = Record<IconLibraryName, Set<string>>

async function findTsxFiles(dir: string) {
  const files: string[] = []
  await fs.readdir(dir, { withFileTypes: true }).then(async (entries) => {
    for (const entry of entries) {
      const fullPath = path.join(dir, entry.name)
      if (entry.isDirectory()) {
        findTsxFiles(fullPath).then((tsxFiles) => {
          files.push(...tsxFiles)
        })
      } else if (entry.isFile() && entry.name.endsWith(".tsx")) {
        files.push(fullPath)
      }
    }
  })
  return files
}

async function scanIconUsage() {
  const iconUsage: IconUsage = Object.keys(iconLibraries).reduce((acc, key) => {
    acc[key as IconLibraryName] = new Set()
    return acc
  }, {} as IconUsage)

  const registryBasesDir = path.join(process.cwd(), "components")
  const files = await findTsxFiles(registryBasesDir)
  const libraryNames = Object.values(iconLibraries)
    .map((lib) => lib.name)
    .join("|")
  const iconPlaceholderRegex = new RegExp(
    `<IconPlaceholder\\s+([^>]*?)(?:${libraryNames})=["']([^"']+)["']([^>]*?)\\/?>`,
    "g"
  )

  for (const file of files) {
    const content = await fs.readFile(file, "utf-8")

    let match: any
    // biome-ignore lint/suspicious/noAssignInExpressions: false-positive
    while ((match = iconPlaceholderRegex.exec(content)) !== null) {
      const fullMatch = match[0]

      for (const [libraryName, config] of Object.entries(iconLibraries)) {
        const attrMatch = fullMatch.match(new RegExp(`${config.name}=["']([^"']+)["']`))
        if (attrMatch) {
          iconUsage[libraryName as IconLibraryName].add(attrMatch[1])
        }
      }
    }
  }

  return iconUsage
}

async function generateIconFiles(iconUsage: IconUsage) {
  const outputDir = path.join(process.cwd(), "lib/icons")

  const written: string[] = []

  Object.entries(iconLibraries).forEach(async ([libraryName, config]) => {
    const icons = Array.from(iconUsage[libraryName as IconLibraryName]).sort()

    if (icons.length === 0) {
      return
    }

    const content = `// Auto-generated by scripts/build-icons.ts
${icons.map((icon) => `export { ${icon} } from "${config.export}"`).join("\n")}
`

    const filename = `__${libraryName}__.ts`
    const filepath = path.join(outputDir, filename)

    if ((await fs.readFile(filepath, "utf-8")) === content) return

    await fs.writeFile(filepath, content)
    written.push(`  - ${config.title}: ${icons.length} icons`)
  })

  if (written.length > 0) {
    console.info("✓ Generated icon files:")
    written.forEach(async (line) => console.info(line))
  }
}

async function main() {
  const iconUsage = await scanIconUsage()
  await generateIconFiles(iconUsage)
}

main()
